window.initTzLocation = function(regionId, districtId, wardId, streetId, customStreetId) {
  const rEl = document.getElementById(regionId);
  const dEl = document.getElementById(districtId);
  const wEl = document.getElementById(wardId);
  const sEl = document.getElementById(streetId);
  const cEl = customStreetId ? document.getElementById(customStreetId) : null;
  if (!rEl || !dEl || !wEl || !sEl) return;

  rEl.innerHTML = '<option value="">-- Chagua Mkoa (Mikoa Yote 31) --</option>';
  Object.keys(window.TZ_DATA).sort().forEach(reg => {
    const opt = document.createElement('option');
    opt.value = reg;
    opt.textContent = reg;
    rEl.appendChild(opt);
  });

  rEl.addEventListener('change', () => {
    const reg = rEl.value;
    dEl.innerHTML = '<option value="">-- Chagua Wilaya --</option>';
    wEl.innerHTML = '<option value="">-- Kwanza Chagua Wilaya --</option>';
    sEl.innerHTML = '<option value="">-- Kwanza Chagua Kata --</option>';
    if (reg && window.TZ_DATA[reg]) {
      Object.keys(window.TZ_DATA[reg]).sort().forEach(dist => {
        const opt = document.createElement('option');
        opt.value = dist;
        opt.textContent = dist;
        dEl.appendChild(opt);
      });
    }
  });

  dEl.addEventListener('change', () => {
    const reg = rEl.value;
    const dist = dEl.value;
    wEl.innerHTML = '<option value="">-- Chagua Kata --</option>';
    sEl.innerHTML = '<option value="">-- Kwanza Chagua Kata --</option>';
    if (reg && dist && window.TZ_DATA[reg] && window.TZ_DATA[reg][dist]) {
      Object.keys(window.TZ_DATA[reg][dist]).sort().forEach(ward => {
        const opt = document.createElement('option');
        opt.value = ward;
        opt.textContent = ward;
        wEl.appendChild(opt);
      });
    }
  });

  wEl.addEventListener('change', () => {
    const reg = rEl.value;
    const dist = dEl.value;
    const ward = wEl.value;
    sEl.innerHTML = '<option value="">-- Chagua Mtaa / Kijiji --</option>';
    if (reg && dist && ward && window.TZ_DATA[reg]?.[dist]?.[ward]) {
      window.TZ_DATA[reg][dist][ward].forEach(st => {
        const opt = document.createElement('option');
        opt.value = st;
        opt.textContent = st;
        sEl.appendChild(opt);
      });
    }
    const otherOpt = document.createElement('option');
    otherOpt.value = '__OTHER__';
    otherOpt.textContent = '✏️ Mtaa Mwingine (Andika hapa chini)';
    sEl.appendChild(otherOpt);
  });

  if (cEl) {
    sEl.addEventListener('change', () => {
      if (sEl.value === '__OTHER__') {
        cEl.style.display = 'block';
        cEl.required = true;
      } else {
        cEl.style.display = 'none';
        cEl.required = false;
      }
    });
  }
};